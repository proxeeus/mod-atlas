"""Write the server rows from the same source rows as the client patch:
  atlas_clones.sql    map_dbc, mapdifficulty_dbc, instance_template, atlas_map_source (clones.json)
  atlas_fogs.sql      spell_dbc rows of the fog spells and the atlas_fog table (fogs.json)
  atlas_pool.sql      the generated-map pool map, its kit pieces (gameobject_template, atlas_pool_piece; pool.json)
  data/sql/uninstall/atlas_{clones,fogs}_uninstall.sql    delete exactly the reserved rows (not auto-applied)

  python3 -I gen_sql.py [--client DIR | --dbc-dir DIR] [--check] [--install clones|fogs|pool ...]

Each file goes to data/sql/staged/ (never applied: the updater only reads data/sql/*db-world*) until --install moves
it to data/sql/db-world/base/, where the database updater applies it (on the play setup: ac-db-import after the next
image build). Install only after the world DB backup (STAGE2 6). Once installed, regenerating keeps writing to
base/. --check compares the files on disk with what would be written and exits 1 on a difference.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import clonedata  # noqa: E402
import dbc  # noqa: E402
import fogdata  # noqa: E402
import pooldata  # noqa: E402
from build_patch import DEFAULT_CLIENT  # noqa: E402

SQL = os.path.join(clonedata.MODULE, 'data', 'sql')
PARTS = ('clones', 'fogs', 'pool')


def base_sql(part):
    return os.path.join(SQL, 'db-world', 'base', 'atlas_%s.sql' % part)


def staged_sql(part):
    return os.path.join(SQL, 'staged', 'atlas_%s.sql' % part)


def uninstall_sql(part):
    return os.path.join(SQL, 'uninstall', 'atlas_%s_uninstall.sql' % part)


def part_sql(part):
    """Where atlas_<part>.sql lives now: base/ once installed, staged/ before."""
    return base_sql(part) if os.path.exists(base_sql(part)) else staged_sql(part)


def literal(value, kind):
    if kind == 's':
        return "'" + value.replace('\\', '\\\\').replace("'", "''") + "'"
    if kind == 'f':
        return '%.9g' % value
    return str(value)


def wrap(items, width=119):
    """'(a,b,...)' split over lines of at most `width` characters (continuation lines indented)."""
    lines, cur = [], '('
    for i, item in enumerate(items):
        piece = item + (',' if i + 1 < len(items) else ')')
        if len(cur) + len(piece) > width and cur.strip('( '):
            lines.append(cur)
            cur = '    '
        cur += piece
    lines.append(cur)
    return '\n'.join(lines)


def values(decoded, fields):
    return wrap([literal(v, k) for v, (_, k) in zip(decoded, fields)])


def columns(fields):
    return wrap(['`%s`' % n for n, _ in fields])


def in_list(ids):
    return ','.join(str(i) for i in ids)


def render(map_dbc, md_dbc, added, digest, templates):
    clone_ids = [c['id'] for c, _, _ in added]
    md_ids = [c['mapdifficulty_id'] for c, _, _ in added]
    out = []
    w = out.append
    w('-- mod-atlas: clone maps (stage 2). Generated by tools/clones/gen_sql.py from the client\'s own Map.dbc and')
    w('-- MapDifficulty.dbc, the same rows as client_patch/patch-T.MPQ (rows checksum %s).' % digest)
    w('-- Do not edit by hand: change tools/clones/clones.json and regenerate both.')
    w('--')
    w('-- Reserved IDs only (maps 900-949, MapDifficulty 754+). A clone\'s map_dbc, mapdifficulty_dbc and')
    w('-- instance_template rows are always installed together. The rows are inert: nothing enters a clone unless')
    w('-- mod-atlas sends a run there (Atlas.Clones.Enable and the player\'s opt-in). Uninstall:')
    w('-- data/sql/uninstall/atlas_clones_uninstall.sql.')
    w('')
    w('CREATE TABLE IF NOT EXISTS `atlas_map_source` (')
    w('    `clone_map`  SMALLINT UNSIGNED NOT NULL COMMENT \'clone map ID (900-949)\',')
    w('    `source_map` SMALLINT UNSIGNED NOT NULL COMMENT \'the stock map whose terrain it reuses\',')
    w('    `enabled`    TINYINT UNSIGNED  NOT NULL DEFAULT 0 COMMENT \'runs may open in it\',')
    w('    `name`       VARCHAR(100)      NOT NULL DEFAULT \'\',')
    w('    PRIMARY KEY (`clone_map`)')
    w(') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT=\'mod-atlas: clone map registry\';')
    w('')
    w('-- Remove every reserved clone row first, so a clone dropped from clones.json disappears too.')
    w('DELETE FROM `atlas_map_source` WHERE `clone_map` BETWEEN %d AND %d;' % clonedata.MAP_ID_RANGE)
    w('DELETE FROM `instance_template` WHERE `map` BETWEEN %d AND %d;' % clonedata.MAP_ID_RANGE)
    w('DELETE FROM `mapdifficulty_dbc` WHERE `MapID` BETWEEN %d AND %d;' % clonedata.MAP_ID_RANGE)
    w('DELETE FROM `map_dbc` WHERE `ID` BETWEEN %d AND %d;' % clonedata.MAP_ID_RANGE)
    w('DELETE FROM `mapdifficulty_dbc` WHERE `ID` IN (%s);' % in_list(md_ids))
    w('')
    w('INSERT INTO `map_dbc`\n%s VALUES' % columns(clonedata.MAP_FIELDS))
    rows = [values(clonedata.decode(map_dbc, row, clonedata.MAP_FIELDS), clonedata.MAP_FIELDS)
            for _, row, _ in added]
    w(',\n'.join(rows) + ';')
    w('')
    w('INSERT INTO `mapdifficulty_dbc`\n%s VALUES' % columns(clonedata.MAPDIFFICULTY_FIELDS))
    rows = [values(clonedata.decode(md_dbc, md, clonedata.MAPDIFFICULTY_FIELDS), clonedata.MAPDIFFICULTY_FIELDS)
            for _, _, md in added]
    w(',\n'.join(rows) + ';')
    w('')
    w('-- No stock instance script in a clone (script \'\'); parent and allowMount as the source.')
    w('INSERT INTO `instance_template` (`map`, `parent`, `script`, `allowMount`) VALUES')
    rows = []
    for c, _, _ in added:
        if c['source'] not in templates:
            raise SystemExit('clone %d: source map %d has no instance_template row' % (c['id'], c['source']))
        parent, _, mount = templates[c['source']]
        rows.append("(%d,%d,'',%d)" % (c['id'], parent, mount))
    w(',\n'.join(rows) + ';')
    w('')
    w('INSERT INTO `atlas_map_source` (`clone_map`, `source_map`, `enabled`, `name`) VALUES')
    w(',\n'.join("(%d,%d,1,%s)" % (c['id'], c['source'], literal(c['name'], 's')) for c, _, _ in added) + ';')
    base = '\n'.join(out) + '\n'

    un = []
    u = un.append
    u('-- mod-atlas: removes the clone map rows of atlas_clones.sql (tools/clones/gen_sql.py; reserved IDs only).')
    u('-- Not applied automatically. Run it by hand against acore_world after Atlas.Clones.Enable = 0, the client')
    u('-- patch is removed and the data links are gone (tools/clones/link_data.sh --remove), then restart.')
    u('-- While data/sql/db-world/base/atlas_clones.sql is in the module, the next start installs the rows again: move')
    u('-- it back to data/sql/staged/ first to keep them out.')
    u('')
    u('DELETE FROM `atlas_map_source` WHERE `clone_map` BETWEEN %d AND %d;' % clonedata.MAP_ID_RANGE)
    u('DELETE FROM `instance_template` WHERE `map` BETWEEN %d AND %d;' % clonedata.MAP_ID_RANGE)
    u('DELETE FROM `mapdifficulty_dbc` WHERE `MapID` BETWEEN %d AND %d;' % clonedata.MAP_ID_RANGE)
    u('DELETE FROM `map_dbc` WHERE `ID` BETWEEN %d AND %d;' % clonedata.MAP_ID_RANGE)
    u("DELETE FROM `updates` WHERE `name` = 'atlas_clones.sql';")
    uninstall = '\n'.join(un) + '\n'
    return base, uninstall


def clones_sql():
    return part_sql('clones')


def render_fogs(spells, fogs, digest):
    fields = fogdata.spell_fields()
    out = []
    w = out.append
    w('-- mod-atlas: fogs of map runs (screen effects). Generated by tools/clones/gen_sql.py from fogs.json and the')
    w('-- client\'s own Spell.dbc, the same spell rows as client_patch/patch-T.MPQ (fogs checksum %s).' % digest)
    w('-- Do not edit by hand: change tools/clones/fogs.json and regenerate both.')
    w('--')
    w('-- Each fog is an aura-260 spell (a copy of Mist of the Kvaldir, 50203, with our name, tooltip and screen')
    w('-- effect, removed on map change) that mod-atlas puts on players with the Atlas patch inside a run. The')
    w('-- ScreenEffect rows exist only in the client patch. Reserved spell IDs 90400-90449. Uninstall:')
    w('-- data/sql/uninstall/atlas_fogs_uninstall.sql.')
    w('')
    w('DELETE FROM `spell_dbc` WHERE `ID` BETWEEN %d AND %d;' % fogdata.SPELL_ID_RANGE)
    w('INSERT INTO `spell_dbc`\n%s VALUES' % wrap(['`%s`' % n for n, _ in fields]))
    rows = [wrap([literal(v, k) for v, (_, k) in zip(fogdata.decode_spell(spells, row, fields), fields)])
            for _, _, row in fogs]
    w(',\n'.join(rows) + ';')
    w('')
    w('CREATE TABLE IF NOT EXISTS `atlas_fog` (')
    w('    `id`         INT UNSIGNED     NOT NULL,')
    w('    `theme_id`   INT UNSIGNED     NOT NULL DEFAULT 0   COMMENT \'0 = any theme\',')
    w('    `corruption` TINYINT UNSIGNED NOT NULL DEFAULT 255 COMMENT \'corruption level 0-5, 255 = any\',')
    w('    `affix_id`   INT UNSIGNED     NOT NULL DEFAULT 0   COMMENT \'> 0: an affix fog (wins over the theme)\',')
    w('    `spell_id`   INT UNSIGNED     NOT NULL DEFAULT 0   COMMENT \'fog spell (spell_dbc 90400-90449)\',')
    w('    `comment`    VARCHAR(100)     NOT NULL DEFAULT \'\',')
    w('    PRIMARY KEY (`id`)')
    w(') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT=\'mod-atlas: run fogs\';')
    w('')
    w('DELETE FROM `atlas_fog` WHERE `id` BETWEEN 1 AND 999;')
    w('INSERT INTO `atlas_fog` (`id`, `theme_id`, `corruption`, `affix_id`, `spell_id`, `comment`) VALUES')
    rows = []
    for fog, _, _ in fogs:
        for use in fog['use']:
            rows.append('(%d,%d,%d,%d,%d,%s)' % (len(rows) + 1, use.get('theme', 0), use.get('corruption', 255),
                                                 use.get('affix', 0), fog['spell'], literal(fog['name'], 's')))
    w(',\n'.join(rows) + ';')
    base = '\n'.join(out) + '\n'

    un = ['-- mod-atlas: removes the fog rows of atlas_fogs.sql (tools/clones/gen_sql.py; reserved IDs only).',
          '-- Not applied automatically. Run it by hand against acore_world, then restart. While',
          '-- data/sql/db-world/base/atlas_fogs.sql is in the module, the next update installs the rows again: move',
          '-- it back to data/sql/staged/ first to keep them out.',
          '',
          'DELETE FROM `spell_dbc` WHERE `ID` BETWEEN %d AND %d;' % fogdata.SPELL_ID_RANGE,
          'DROP TABLE IF EXISTS `atlas_fog`;',
          "DELETE FROM `updates` WHERE `name` = 'atlas_fogs.sql';"]
    return base, '\n'.join(un) + '\n'


def render_pool(map_dbc, md_dbc, pool_map, pool_md, cfg):
    lo, hi = pooldata.POOL_MAP_RANGE
    plo, phi = pooldata.PIECE_ENTRY_RANGE
    m = cfg['map']
    out = []
    w = out.append
    w('-- mod-atlas: the generated-map pool (DESIGN 6.2 spike). Generated by tools/clones/gen_sql.py from pool.json')
    w('-- and the client\'s own Map.dbc / MapDifficulty.dbc, the same rows as client_patch/patch-T.MPQ.')
    w('-- Do not edit by hand: change tools/clones/pool.json and regenerate both.')
    w('--')
    w('-- Pool maps (%d-%d) have an empty WDT: no terrain, no vmaps, no mmaps. mod-atlas places kit pieces'
      % (lo, hi))
    w('-- in them as gameobjects (type 14, a stock WMO with a stock display: the server has its collision model).')
    w('-- Inert until used (.atlas spike, opted-in accounts). Uninstall: data/sql/uninstall/atlas_pool_uninstall.sql.')
    w('')
    w('DELETE FROM `instance_template` WHERE `map` BETWEEN %d AND %d;' % (lo, hi))
    w('DELETE FROM `mapdifficulty_dbc` WHERE `MapID` BETWEEN %d AND %d;' % (lo, hi))
    w('DELETE FROM `map_dbc` WHERE `ID` BETWEEN %d AND %d;' % (lo, hi))
    w('DELETE FROM `mapdifficulty_dbc` WHERE `ID` = %d;' % m['mapdifficulty_id'])
    w('')
    w('INSERT INTO `map_dbc`\n%s VALUES' % columns(clonedata.MAP_FIELDS))
    w(values(clonedata.decode(map_dbc, pool_map, clonedata.MAP_FIELDS), clonedata.MAP_FIELDS) + ';')
    w('')
    w('INSERT INTO `mapdifficulty_dbc`\n%s VALUES' % columns(clonedata.MAPDIFFICULTY_FIELDS))
    w(values(clonedata.decode(md_dbc, pool_md, clonedata.MAPDIFFICULTY_FIELDS), clonedata.MAPDIFFICULTY_FIELDS) + ';')
    w('')
    w('INSERT INTO `instance_template` (`map`, `parent`, `script`, `allowMount`) VALUES')
    w("(%d,0,'',0);" % m['id'])
    w('')
    w('-- Kit pieces: type 14 (MAP_OBJECT), the room is the display\'s WMO.')
    w('DELETE FROM `gameobject_template` WHERE `entry` BETWEEN %d AND %d;' % (plo, phi))
    w('INSERT INTO `gameobject_template` (`entry`, `type`, `displayId`, `name`, `IconName`, `size`, `ScriptName`) '
      'VALUES')
    w(',\n'.join("(%d,14,%d,%s,'',1.0,'')" % (p['go_entry'], p['display'], literal(p['name'], 's'))
                 for p in cfg['pieces']) + ';')
    w('')
    w('CREATE TABLE IF NOT EXISTS `atlas_pool_piece` (')
    w('    `go_entry`   INT UNSIGNED NOT NULL COMMENT \'gameobject_template entry (900100-900199)\',')
    w('    `map`        SMALLINT UNSIGNED NOT NULL COMMENT \'pool map (950-999)\',')
    w('    `x`          FLOAT NOT NULL DEFAULT 0,')
    w('    `y`          FLOAT NOT NULL DEFAULT 0,')
    w('    `z`          FLOAT NOT NULL DEFAULT 0,')
    w('    `o`          FLOAT NOT NULL DEFAULT 0,')
    w('    `entrance_x` FLOAT NOT NULL DEFAULT 0 COMMENT \'where players arrive, on the floor of the piece\',')
    w('    `entrance_y` FLOAT NOT NULL DEFAULT 0,')
    w('    `entrance_z` FLOAT NOT NULL DEFAULT 0,')
    w('    PRIMARY KEY (`go_entry`)')
    w(') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT=\'mod-atlas: pool map kit pieces\';')
    w('')
    w('DELETE FROM `atlas_pool_piece` WHERE `go_entry` BETWEEN %d AND %d;' % (plo, phi))
    w('INSERT INTO `atlas_pool_piece` (`go_entry`, `map`, `x`, `y`, `z`, `o`, `entrance_x`, `entrance_y`, '
      '`entrance_z`) VALUES')
    rows = []
    for p in cfg['pieces']:
        ex, ey, ez = pooldata.entrance(p)
        rows.append('(%d,%d,%s,%s,%s,%s,%s,%s,%s)' % ((p['go_entry'], m['id']) + tuple(
            literal(v, 'f') for v in list(p['position']) + [ex, ey, ez])))
    w(',\n'.join(rows) + ';')
    base = '\n'.join(out) + '\n'

    un = ['-- mod-atlas: removes the pool rows of atlas_pool.sql (tools/clones/gen_sql.py; reserved IDs only).',
          '-- Not applied automatically. Run it by hand against acore_world, then restart. While',
          '-- data/sql/db-world/base/atlas_pool.sql is in the module, the next update installs the rows again: move',
          '-- it back to data/sql/staged/ first to keep them out.',
          '',
          'DELETE FROM `instance_template` WHERE `map` BETWEEN %d AND %d;' % (lo, hi),
          'DELETE FROM `mapdifficulty_dbc` WHERE `MapID` BETWEEN %d AND %d;' % (lo, hi),
          'DELETE FROM `map_dbc` WHERE `ID` BETWEEN %d AND %d;' % (lo, hi),
          'DELETE FROM `gameobject_template` WHERE `entry` BETWEEN %d AND %d;' % (plo, phi),
          'DROP TABLE IF EXISTS `atlas_pool_piece`;',
          "DELETE FROM `updates` WHERE `name` = 'atlas_pool.sql';"]
    return base, '\n'.join(un) + '\n'


def fog_checksum(spells, fogs):
    import hashlib
    h = hashlib.sha1()
    fields = fogdata.spell_fields()
    for fog, effect, row in fogs:
        h.update(repr(effect).encode())
        h.update(repr(fogdata.decode_spell(spells, row, fields)).encode())
    return h.hexdigest()[:16]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--client', default=DEFAULT_CLIENT, help='client folder (read-only)')
    ap.add_argument('--dbc-dir', help='read Map.dbc and MapDifficulty.dbc from this folder instead of the client')
    ap.add_argument('--check', action='store_true', help='only compare with the files on disk')
    ap.add_argument('--install', action='append', choices=PARTS, default=[],
                    help='write atlas_<part>.sql to db-world/base/ (applied by the next update), drop the staged one')
    args = ap.parse_args()

    cfg = clonedata.load_config()
    client = args.client if not args.dbc_dir else None
    map_dbc, md_dbc, _ = clonedata.source_dbcs(client, args.dbc_dir, cfg['patch_name'])
    added = clonedata.add_clones(map_dbc, md_dbc, clonedata.enabled(cfg))
    digest = clonedata.checksum(map_dbc, md_dbc, added)
    texts = {'clones': render(map_dbc, md_dbc, added, digest, clonedata.source_instance_templates())}
    pool_cfg = pooldata.load_config()
    pool_map, pool_md = pooldata.add_pool(map_dbc, md_dbc, pool_cfg)
    texts['pool'] = render_pool(map_dbc, md_dbc, pool_map, pool_md, pool_cfg)

    raw_effects, _ = clonedata.effective_raw(client, args.dbc_dir, 'ScreenEffect.dbc', cfg['patch_name'])
    raw_spells, _ = clonedata.effective_raw(client, args.dbc_dir, 'Spell.dbc', cfg['patch_name'])
    spells = dbc.RawDbc(raw_spells)
    fogs = fogdata.add_fogs(dbc.Dbc.parse(raw_effects), spells, fogdata.load_config())
    fog_digest = fog_checksum(spells, fogs)
    texts['fogs'] = render_fogs(spells, fogs, fog_digest)

    writes = []
    for part in PARTS:
        target = base_sql(part) if part in args.install else part_sql(part)
        writes += [(target, texts[part][0]), (uninstall_sql(part), texts[part][1])]

    stale = False
    for path, text in writes:
        current = open(path, encoding='utf8').read() if os.path.exists(path) else None
        if args.check:
            if current != text:
                print('differs: %s' % path)
                stale = True
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w', encoding='utf8', newline='\n') as f:
            f.write(text)
        print('wrote %s' % path)
    for part in args.install:
        if not args.check and os.path.exists(staged_sql(part)):
            os.remove(staged_sql(part))
            print('removed %s' % staged_sql(part))
    print('clones %s, rows checksum %s' % ([c['id'] for c, _, _ in added], digest))
    print('fogs %s, fogs checksum %s' % ([f['spell'] for f, _, _ in fogs], fog_digest))
    sys.exit(1 if stale else 0)


if __name__ == '__main__':
    main()
