"""Write the server rows of the enabled clones from the same source rows as the client patch:
  atlas_clones.sql                                 map_dbc, mapdifficulty_dbc, instance_template, atlas_map_source
  data/sql/uninstall/atlas_clones_uninstall.sql    deletes exactly the reserved rows (not auto-applied)

  python3 -I gen_sql.py [--client DIR | --dbc-dir DIR] [--check] [--install]

atlas_clones.sql goes to data/sql/staged/ (never applied: the updater only reads data/sql/*db-world*) until
--install moves it to data/sql/db-world/base/, where the database updater applies it (on the play setup: ac-db-import
after the next image build). Install only after the world DB backup (STAGE2 6). Once installed, regenerating keeps
writing to base/. --check compares the files on disk with what would be written and exits 1 on a difference.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import clonedata  # noqa: E402
from build_patch import DEFAULT_CLIENT  # noqa: E402

BASE_SQL = os.path.join(clonedata.MODULE, 'data', 'sql', 'db-world', 'base', 'atlas_clones.sql')
STAGED_SQL = os.path.join(clonedata.MODULE, 'data', 'sql', 'staged', 'atlas_clones.sql')
UNINSTALL_SQL = os.path.join(clonedata.MODULE, 'data', 'sql', 'uninstall', 'atlas_clones_uninstall.sql')


def literal(value, kind):
    if kind == 's':
        return "'" + value.replace('\\', '\\\\').replace("'", "''") + "'"
    if kind == 'f':
        return '%.9g' % value
    return str(value)


def wrap(items, width=119):
    """'(a,b,...)' split over lines of at most `width` characters (continuation lines indented)."""
    lines, cur = [], '('
    for i, item in enumerate(items):
        piece = item + (',' if i + 1 < len(items) else ')')
        if len(cur) + len(piece) > width and cur.strip('( '):
            lines.append(cur)
            cur = '    '
        cur += piece
    lines.append(cur)
    return '\n'.join(lines)


def values(decoded, fields):
    return wrap([literal(v, k) for v, (_, k) in zip(decoded, fields)])


def columns(fields):
    return wrap(['`%s`' % n for n, _ in fields])


def in_list(ids):
    return ','.join(str(i) for i in ids)


def render(map_dbc, md_dbc, added, digest, templates):
    clone_ids = [c['id'] for c, _, _ in added]
    md_ids = [c['mapdifficulty_id'] for c, _, _ in added]
    out = []
    w = out.append
    w('-- mod-atlas: clone maps (stage 2). Generated by tools/clones/gen_sql.py from the client\'s own Map.dbc and')
    w('-- MapDifficulty.dbc, the same rows as client_patch/patch-T.MPQ (rows checksum %s).' % digest)
    w('-- Do not edit by hand: change tools/clones/clones.json and regenerate both.')
    w('--')
    w('-- Reserved IDs only (maps 900-949, MapDifficulty 754+). A clone\'s map_dbc, mapdifficulty_dbc and')
    w('-- instance_template rows are always installed together. The rows are inert: nothing enters a clone unless')
    w('-- mod-atlas sends a run there (Atlas.Clones.Enable and the player\'s opt-in). Uninstall:')
    w('-- data/sql/uninstall/atlas_clones_uninstall.sql.')
    w('')
    w('CREATE TABLE IF NOT EXISTS `atlas_map_source` (')
    w('    `clone_map`  SMALLINT UNSIGNED NOT NULL COMMENT \'clone map ID (900-949)\',')
    w('    `source_map` SMALLINT UNSIGNED NOT NULL COMMENT \'the stock map whose terrain it reuses\',')
    w('    `enabled`    TINYINT UNSIGNED  NOT NULL DEFAULT 0 COMMENT \'runs may open in it\',')
    w('    `name`       VARCHAR(100)      NOT NULL DEFAULT \'\',')
    w('    PRIMARY KEY (`clone_map`)')
    w(') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT=\'mod-atlas: clone map registry\';')
    w('')
    w('-- Remove every reserved clone row first, so a clone dropped from clones.json disappears too.')
    w('DELETE FROM `atlas_map_source` WHERE `clone_map` BETWEEN %d AND %d;' % clonedata.MAP_ID_RANGE)
    w('DELETE FROM `instance_template` WHERE `map` BETWEEN %d AND %d;' % clonedata.MAP_ID_RANGE)
    w('DELETE FROM `mapdifficulty_dbc` WHERE `MapID` BETWEEN %d AND %d;' % clonedata.MAP_ID_RANGE)
    w('DELETE FROM `map_dbc` WHERE `ID` BETWEEN %d AND %d;' % clonedata.MAP_ID_RANGE)
    w('DELETE FROM `mapdifficulty_dbc` WHERE `ID` IN (%s);' % in_list(md_ids))
    w('')
    w('INSERT INTO `map_dbc`\n%s VALUES' % columns(clonedata.MAP_FIELDS))
    rows = [values(clonedata.decode(map_dbc, row, clonedata.MAP_FIELDS), clonedata.MAP_FIELDS)
            for _, row, _ in added]
    w(',\n'.join(rows) + ';')
    w('')
    w('INSERT INTO `mapdifficulty_dbc`\n%s VALUES' % columns(clonedata.MAPDIFFICULTY_FIELDS))
    rows = [values(clonedata.decode(md_dbc, md, clonedata.MAPDIFFICULTY_FIELDS), clonedata.MAPDIFFICULTY_FIELDS)
            for _, _, md in added]
    w(',\n'.join(rows) + ';')
    w('')
    w('-- No stock instance script in a clone (script \'\'); parent and allowMount as the source.')
    w('INSERT INTO `instance_template` (`map`, `parent`, `script`, `allowMount`) VALUES')
    rows = []
    for c, _, _ in added:
        if c['source'] not in templates:
            raise SystemExit('clone %d: source map %d has no instance_template row' % (c['id'], c['source']))
        parent, _, mount = templates[c['source']]
        rows.append("(%d,%d,'',%d)" % (c['id'], parent, mount))
    w(',\n'.join(rows) + ';')
    w('')
    w('INSERT INTO `atlas_map_source` (`clone_map`, `source_map`, `enabled`, `name`) VALUES')
    w(',\n'.join("(%d,%d,1,%s)" % (c['id'], c['source'], literal(c['name'], 's')) for c, _, _ in added) + ';')
    base = '\n'.join(out) + '\n'

    un = []
    u = un.append
    u('-- mod-atlas: removes the clone map rows of atlas_clones.sql (tools/clones/gen_sql.py; reserved IDs only).')
    u('-- Not applied automatically. Run it by hand against acore_world after Atlas.Clones.Enable = 0, the client')
    u('-- patch is removed and the data links are gone (tools/clones/link_data.sh --remove), then restart.')
    u('-- While data/sql/db-world/base/atlas_clones.sql is in the module, the next start installs the rows again: move')
    u('-- it back to data/sql/staged/ first to keep them out.')
    u('')
    u('DELETE FROM `atlas_map_source` WHERE `clone_map` BETWEEN %d AND %d;' % clonedata.MAP_ID_RANGE)
    u('DELETE FROM `instance_template` WHERE `map` BETWEEN %d AND %d;' % clonedata.MAP_ID_RANGE)
    u('DELETE FROM `mapdifficulty_dbc` WHERE `MapID` BETWEEN %d AND %d;' % clonedata.MAP_ID_RANGE)
    u('DELETE FROM `map_dbc` WHERE `ID` BETWEEN %d AND %d;' % clonedata.MAP_ID_RANGE)
    u("DELETE FROM `updates` WHERE `name` = 'atlas_clones.sql';")
    uninstall = '\n'.join(un) + '\n'
    return base, uninstall


def clones_sql():
    """Where atlas_clones.sql lives now: base/ once installed, staged/ before."""
    return BASE_SQL if os.path.exists(BASE_SQL) else STAGED_SQL


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--client', default=DEFAULT_CLIENT, help='client folder (read-only)')
    ap.add_argument('--dbc-dir', help='read Map.dbc and MapDifficulty.dbc from this folder instead of the client')
    ap.add_argument('--check', action='store_true', help='only compare with the files on disk')
    ap.add_argument('--install', action='store_true',
                    help='write atlas_clones.sql to db-world/base/ (applied by the next update), drop the staged one')
    args = ap.parse_args()

    cfg = clonedata.load_config()
    map_dbc, md_dbc, _ = clonedata.source_dbcs(args.client if not args.dbc_dir else None, args.dbc_dir,
                                               cfg['patch_name'])
    added = clonedata.add_clones(map_dbc, md_dbc, clonedata.enabled(cfg))
    digest = clonedata.checksum(map_dbc, md_dbc, added)
    base, uninstall = render(map_dbc, md_dbc, added, digest, clonedata.source_instance_templates())

    target = BASE_SQL if args.install else clones_sql()
    stale = False
    for path, text in ((target, base), (UNINSTALL_SQL, uninstall)):
        current = open(path, encoding='utf8').read() if os.path.exists(path) else None
        if args.check:
            if current != text:
                print('differs: %s' % path)
                stale = True
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w', encoding='utf8', newline='\n') as f:
            f.write(text)
        print('wrote %s' % path)
    if args.install and not args.check and os.path.exists(STAGED_SQL):
        os.remove(STAGED_SQL)
        print('removed %s' % STAGED_SQL)
    print('clones %s, rows checksum %s' % ([c['id'] for c, _, _ in added], digest))
    sys.exit(1 if stale else 0)


if __name__ == '__main__':
    main()
