"""The generated-map pool (pool.json): Map.dbc, MapDifficulty.dbc and AreaTable.dbc rows of a pool map that has no
terrain, its WDT, and the kit pieces mod-atlas places in it as gameobjects: our own tileset (kit.json), generated by
kitwmo.py (client WMOs) and kitvmo.py (server collision), with GameObjectDisplayInfo rows of our own.

The WDT has no terrain tiles, only a global WMO (MPHD flag 1, one MWMO name, one MODF placement; Wowdecomp2
CMap::LoadWdt, WorldClient/Map.cpp:2892): a copy of the first piece's WMO far below the play space, never seen. It
is there because the client takes a map's zone (name, music, ambience) from Map.dbc AreaTableID only for a map with
a global WMO (World::QueryAreaIdAtPosition, World.cpp:4674, CMap::bDungeon); without one it looks for terrain under
the player, finds none and keeps the zone it came from. A missing WDL is skipped (MapLowDetail.cpp:123).

The server takes the zone from Map.dbc AreaTableID too when nothing under the player gives one (Map::
GetFullTerrainStatusForPosition, linked_zone), so the same area row goes into areatable_dbc.
"""
import json
import os
import struct

import clonedata
import dbc
import kitvmo
import kitwmo

POOL_MAP_RANGE = (950, 999)
PIECE_ENTRY_RANGE = (900100, 900199)
DISPLAY_ID_RANGE = (9900, 9949)
WMO_ID_RANGE = (7900, 7949)
AREA_ID_RANGE = (7900, 7949)
AREA_BIT_MAX = 4095  # the server keeps 128 x 32 explored-zone bits (PLAYER_EXPLORED_ZONES_SIZE)
DBC_GO_DISPLAY = 'DBFilesClient\\GameObjectDisplayInfo.dbc'
DBC_AREATABLE = 'DBFilesClient\\AreaTable.dbc'

# AreaTable.dbc (3.3.5a), the column order of `areatable_dbc`.
AREATABLE_FIELDS = ([('ID', 'i'), ('ContinentID', 'i'), ('ParentAreaID', 'i'), ('AreaBit', 'i'), ('Flags', 'i'),
                     ('SoundProviderPref', 'i'), ('SoundProviderPrefUnderwater', 'i'), ('AmbienceID', 'i'),
                     ('ZoneMusic', 'i'), ('IntroSound', 'i'), ('ExplorationLevel', 'i')]
                    + clonedata._lang('AreaName')
                    + [('FactionGroupMask', 'i'), ('LiquidTypeID_1', 'i'), ('LiquidTypeID_2', 'i'),
                       ('LiquidTypeID_3', 'i'), ('LiquidTypeID_4', 'i'), ('MinElevation', 'f'),
                       ('Ambient_Multiplier', 'f'), ('Lightid', 'i')])
assert len(AREATABLE_FIELDS) == 36
# GameObjectDisplayInfo.dbc (3.3.5a), the column order of `gameobjectdisplayinfo_dbc`.
GODISPLAY_FIELDS = ([('ID', 'i'), ('ModelName', 's')] + [('Sound_%d' % i, 'i') for i in range(1, 11)]
                    + [('GeoBoxMinX', 'f'), ('GeoBoxMinY', 'f'), ('GeoBoxMinZ', 'f'), ('GeoBoxMaxX', 'f'),
                       ('GeoBoxMaxY', 'f'), ('GeoBoxMaxZ', 'f'), ('ObjectEffectPackageID', 'i')])
assert len(GODISPLAY_FIELDS) == 19
AREA_NAME_ENUS = 11
MAP_AREATABLE = [n for n, _ in clonedata.MAP_FIELDS].index('AreaTableID')
GLOBAL_WMO_DEPTH = 3000.0  # yards below the piece: beyond any view distance


def load_config(path=None):
    with open(path or os.path.join(clonedata.HERE, 'pool.json')) as f:
        cfg = json.load(f)
    m = cfg['map']
    if not POOL_MAP_RANGE[0] <= m['id'] <= POOL_MAP_RANGE[1]:
        raise ValueError('pool map %d outside %d-%d' % (m['id'], *POOL_MAP_RANGE))
    if m['mapdifficulty_id'] < clonedata.MAPDIFFICULTY_ID_MIN:
        raise ValueError('pool MapDifficulty %d below %d' % (m['mapdifficulty_id'], clonedata.MAPDIFFICULTY_ID_MIN))
    clone_md = {c['mapdifficulty_id'] for c in clonedata.load_config()['clones']}
    if m['mapdifficulty_id'] in clone_md:
        raise ValueError('pool MapDifficulty %d is taken by a clone in clones.json' % m['mapdifficulty_id'])
    cfg['pieces'] = kit_pieces()
    entries = {p['go_entry'] for p in cfg['pieces']}
    if m['start'] not in entries:
        raise ValueError('pool map start piece %d is not in pieces' % m['start'])
    if len(m['origin']) != 4 or m['max_pieces'] < 1:
        raise ValueError('pool map needs origin [x, y, z, facing] and max_pieces >= 1')
    a = cfg['area']
    if not AREA_ID_RANGE[0] <= a['id'] <= AREA_ID_RANGE[1]:
        raise ValueError('pool area %d outside %d-%d' % (a['id'], *AREA_ID_RANGE))
    if not 0 < a['area_bit'] <= AREA_BIT_MAX:
        raise ValueError('pool area bit %d outside 1-%d' % (a['area_bit'], AREA_BIT_MAX))
    return cfg


def wdt_path(cfg):
    d = cfg['map']['directory']
    return 'World\\Maps\\%s\\%s.wdt' % (d, d)


def wmo_header(raw):
    """(wmoID, bounding box (x0, y0, z0, x1, y1, z1)) from a root WMO's MOHD chunk."""
    if raw[0:4][::-1] != b'MVER' or raw[12:16][::-1] != b'MOHD':
        raise SystemExit('not a root WMO (no MVER, MOHD)')
    mohd = raw[20:20 + struct.unpack_from('<I', raw, 16)[0]]
    return struct.unpack_from('<I', mohd, 32)[0], struct.unpack_from('<6f', mohd, 36)


def kit_pieces(path=None):
    """The tileset (kit.json) as pool pieces: ids, role, client files, collision geometry, sockets, entrance, box."""
    out, seen = [], set()
    for spec in kitwmo.load_kit(path)['pieces']:
        for key, (lo, hi) in (('go_entry', PIECE_ENTRY_RANGE), ('display', DISPLAY_ID_RANGE),
                              ('wmo_id', WMO_ID_RANGE)):
            if not lo <= spec[key] <= hi:
                raise ValueError('kit piece %s: %s %d outside %d-%d' % (spec['file'], key, spec[key], lo, hi))
            if (key, spec[key]) in seen:
                raise ValueError('kit piece %s: %s %d used twice' % (spec['file'], key, spec[key]))
            seen.add((key, spec[key]))
        if spec['role'] not in ('piece', 'cap'):
            raise ValueError('kit piece %s: role must be piece or cap' % spec['file'])
        files, info = kitwmo.build_files(spec)
        out.append({'go_entry': spec['go_entry'], 'display': spec['display'], 'name': spec['name'],
                    'file': spec['file'], 'wmo': kitwmo.wmo_path(spec), 'role': spec['role'],
                    'entrance_local': info['entrance'], 'sockets': info['sockets'], 'bounds': info['bounds'],
                    'files': files, 'verts': info['verts'], 'tris': info['tris'], 'groups': info['groups'],
                    'model': kitvmo.model_name(spec)})
    return out


def start_piece(cfg):
    return next(p for p in cfg['pieces'] if p['go_entry'] == cfg['map']['start'])


def global_wmo_position(cfg):
    """World position of the global WMO: under the layout's origin, out of sight."""
    ox, oy, oz, _ = cfg['map']['origin']
    return ox, oy, oz - GLOBAL_WMO_DEPTH


def pool_wdt(cfg, bbox):
    """MVER 18, MPHD (flag 1: global WMO), MAIN (64 x 64 tiles, none present), MWMO (the start piece's WMO) and its
    MODF placement. A global WMO is placed in raw world coordinates (no tile offset), stored as file = (-y, z, -x)
    (the inverse of CMap::LoadWdt); `bbox` is the WMO's own (MOHD) bounding box, unrotated."""
    def chunk(tag, data):
        return tag[::-1].encode('ascii') + struct.pack('<I', len(data)) + data

    wx, wy, wz = global_wmo_position(cfg)
    x0, y0, z0, x1, y1, z1 = bbox
    lo = (-(wy + y1), wz + z0, -(wx + x1))
    hi = (-(wy + y0), wz + z1, -(wx + x0))
    name = start_piece(cfg)['wmo'].encode('ascii') + b'\0'
    # Yaw 180: the client adds half a turn to a WDT placement (RotateAroundZ(rotZ + pi)), so this one is unrotated
    # and its extents are the plain box.
    modf = struct.pack('<II3f3f3f3fHHHH', 0, 0, -wy, wz, -wx, 0.0, 180.0, 0.0, *lo, *hi, 0, 0, 0, 0)
    assert len(modf) == 64
    return (chunk('MVER', struct.pack('<I', 18)) + chunk('MPHD', struct.pack('<I', 1) + bytes(28))
            + chunk('MAIN', bytes(64 * 64 * 8)) + chunk('MWMO', name) + chunk('MODF', modf))


def client_inputs(client, dbc_dir, cfg, patch_name='patch-T.MPQ'):
    """(AreaTable.dbc with the pool area added, the area's raw row, the WDT, {go_entry: WMO box}, where) from the
    client's own AreaTable.dbc (read-only, or from `dbc_dir`) and the generated kit."""
    raw_area, where = clonedata.effective_raw(client, dbc_dir, 'AreaTable.dbc', patch_name)
    area_dbc = dbc.Dbc.parse(raw_area)
    row = add_area(area_dbc, cfg)
    boxes = {p['go_entry']: p['bounds'] for p in cfg['pieces']}
    return area_dbc, row, pool_wdt(cfg, boxes[cfg['map']['start']]), boxes, where


def _f32bits(x):
    return struct.unpack('<I', struct.pack('<f', x))[0]


def add_displays(display_dbc, cfg):
    """Append a GameObjectDisplayInfo row per kit piece (its WMO and box). Returns the raw rows."""
    taken = [i for i in display_dbc.ids() if DISPLAY_ID_RANGE[0] <= i <= DISPLAY_ID_RANGE[1]]
    if taken:
        raise SystemExit('GameObjectDisplayInfo.dbc already has rows %s (is an old patch-T.MPQ in the order?)' % taken)
    rows = []
    for p in cfg['pieces']:
        row = [p['display'], display_dbc.add_string(p['wmo'])] + [0] * 10
        row += [_f32bits(v) for v in p['bounds']] + [0]
        display_dbc.rows.append(row)
        rows.append(row)
    display_dbc.rows.sort(key=lambda r: r[0])
    return rows


def add_area(area_dbc, cfg):
    """Append the pool map's area (a copy of the template area's, as a zone of the pool map with no flags, our ID,
    name and explore bit). Returns the raw row."""
    a = cfg['area']
    src = area_dbc.row(a['template'])
    if not src:
        raise SystemExit('pool area template %d has no AreaTable.dbc row' % a['template'])
    if a['id'] in area_dbc.ids():
        raise SystemExit('AreaTable.dbc already has a row %d' % a['id'])
    if any(r[3] == a['area_bit'] for r in area_dbc.rows):
        raise SystemExit('AreaTable.dbc: explore bit %d is used by another area' % a['area_bit'])
    row = list(src)
    row[0] = a['id']
    row[1] = cfg['map']['id']
    row[2] = 0           # a zone, not a subzone
    row[3] = a['area_bit']
    row[4] = 0           # no rest, sanctuary, capital or PvP flags
    row[10] = 0          # no exploration experience
    row[AREA_NAME_ENUS] = area_dbc.add_string(a['name'])
    row[28] = 0          # FactionGroupMask
    area_dbc.rows.append(row)
    area_dbc.rows.sort(key=lambda r: r[0])
    return row


def add_pool(map_dbc, md_dbc, cfg):
    """Append the pool map's rows (a copy of the template map's, with our ID, Directory, name and area)."""
    m = cfg['map']
    src = map_dbc.row(m['template'])
    if not src:
        raise SystemExit('pool template map %d has no Map.dbc row' % m['template'])
    if m['id'] in map_dbc.ids():
        raise SystemExit('Map.dbc already has a row %d' % m['id'])
    if m['mapdifficulty_id'] in md_dbc.ids():
        raise SystemExit('MapDifficulty.dbc already has a row %d' % m['mapdifficulty_id'])
    src_md = [r for r in md_dbc.rows if r[1] == m['template'] and r[2] == 0]
    if len(src_md) != 1:
        raise SystemExit('pool template map %d: expected one normal MapDifficulty row' % m['template'])

    row = list(src)
    row[0] = m['id']
    row[1] = map_dbc.add_string(m['directory'])
    row[clonedata.MAP_NAME_ENUS] = map_dbc.add_string(m['name'])
    row[MAP_AREATABLE] = cfg['area']['id']
    md = list(src_md[0])
    md[0] = m['mapdifficulty_id']
    md[1] = m['id']
    map_dbc.rows.append(row)
    md_dbc.rows.append(md)
    map_dbc.rows.sort(key=lambda r: r[0])
    md_dbc.rows.sort(key=lambda r: r[0])
    return row, md


def display_values(p):
    """The `gameobjectdisplayinfo_dbc` row of a kit piece (GODISPLAY_FIELDS order)."""
    return [p['display'], p['wmo']] + [0] * 10 + [float(v) for v in p['bounds']] + [0]
