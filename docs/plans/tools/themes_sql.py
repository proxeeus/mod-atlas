"""Generate mod-atlas's atlas_themes.sql from the SCOURGE appendix.

Usage: python3 -I themes_sql.py <SCOURGE.md> <out.sql>
Section 4 rows (core pool) give an entry, its pack role and its status (S, P,
F); section 5 rows (rares and minibosses) become both `rare` and `boss`.
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
txt = open(src).read()
sec4 = txt[txt.index('## 4. Core pool'):txt.index('## 5. Rares')]
sec5 = txt[txt.index('## 5. Rares'):txt.index('## 6. Bosses')]

NOTES = {'S': 'SmartAI', 'P': 'plain, melee only', 'F': 'factory-scripted C++: melee only outside its instance'}

pool = []        # (entry, name, role)
curation = {}    # entry -> (status letter, note)

for line in sec4.splitlines():
    if not re.match(r'\|\s*\d{4,6}\s*\|', line):
        continue
    cells = [c.strip() for c in line.strip('|').split('|')]
    entry, name = int(cells[0]), cells[1]
    role = None
    for c in cells[2:]:
        m = re.match(r'(leader|heavy|melee|caster|swarm|add)\b', c)
        if m:
            role = m.group(1)
            break
    if not role:
        raise SystemExit('no role for %s' % line)
    pool.append((entry, name, role))
    status = cells[-1][:1]
    curation[entry] = (status, NOTES.get(status, cells[-1]))

for line in sec5.splitlines():
    if not re.match(r'\|\s*\d{4,6}', line):
        continue
    cells = [c.strip() for c in line.strip('|').split('|')]
    pairs = re.findall(r'(\d{4,6})\s*,?\s*([^,|]*)', cells[0] + ' ' + cells[1]) if ',' in cells[1] else \
        [(cells[0], cells[1])]
    status_cell = cells[-2] if len(cells) > 3 else ''
    for e, n in pairs:
        e = int(e)
        n = n.strip() or cells[1]
        for role in ('rare', 'boss'):
            pool.append((e, n, role))
        letter = status_cell[:1] if status_cell[:1] in NOTES else 'F'
        curation.setdefault(e, (letter, NOTES.get(letter, status_cell)))


def q(s):
    return "'" + s.replace("'", "''") + "'"


lines = [
    '-- =============================================',
    '-- mod-atlas - Themes and the Scourge pool (PLAN 1.3, DESIGN section 8)',
    '-- =============================================',
    '-- Generated by .agents/plans/atlas-endgame/tools/themes_sql.py from the',
    '-- SCOURGE appendix; regenerate rather than edit by hand.',
    '--',
    '-- atlas_theme: database themes beside the config ones (Atlas.Theme.N, by',
    '-- creature type). kind `native`: each dungeon keeps its own inhabitants (its',
    '-- stock spawns); kind `pool`: creatures listed in atlas_theme_creature with a',
    '-- pack role. IDs stay below 100 (gossip menus encode theme IDs).',
    '-- atlas_creature_curation: allowed / untested spawn, blocked never does',
    '-- (`.atlas curate` edits it).',
    '-- =============================================',
    '',
    'CREATE TABLE IF NOT EXISTS `atlas_theme` (',
    '    `id`          INT UNSIGNED     NOT NULL,',
    "    `kind`        VARCHAR(16)      NOT NULL COMMENT 'native or pool',",
    '    `name`        VARCHAR(100)     NOT NULL,',
    "    `description` VARCHAR(255)     NOT NULL DEFAULT '',",
    '    `sort_order`  INT              NOT NULL DEFAULT 0,',
    '    `enabled`     TINYINT UNSIGNED NOT NULL DEFAULT 1,',
    '    PRIMARY KEY (`id`)',
    ') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;',
    '',
    'CREATE TABLE IF NOT EXISTS `atlas_theme_creature` (',
    '    `theme_id`  INT UNSIGNED NOT NULL,',
    '    `entry`     INT UNSIGNED NOT NULL,',
    "    `pack_role` VARCHAR(16)  NOT NULL COMMENT 'leader, heavy, melee, caster, swarm, add, rare, boss',",
    '    `weight`    INT UNSIGNED NOT NULL DEFAULT 100,',
    '    PRIMARY KEY (`theme_id`, `entry`, `pack_role`)',
    ') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;',
    '',
    'CREATE TABLE IF NOT EXISTS `atlas_creature_curation` (',
    '    `entry`  INT UNSIGNED NOT NULL,',
    "    `status` VARCHAR(16)  NOT NULL DEFAULT 'untested' COMMENT 'allowed, untested, blocked',",
    "    `note`   VARCHAR(255) NOT NULL DEFAULT '',",
    '    PRIMARY KEY (`entry`)',
    ') ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;',
    '',
    'DELETE FROM `atlas_theme` WHERE `id` IN (50, 51);',
    'INSERT INTO `atlas_theme` (`id`, `kind`, `name`, `description`, `sort_order`, `enabled`) VALUES',
    "(50, 'native', 'The timeline as it was', 'Its own inhabitants hold the halls', 0, 1),",
    "(51, 'pool', 'A timeline the Scourge swallowed', 'The Lich King''s plague holds every hall', 1, 1);",
    '',
    'DELETE FROM `atlas_theme_creature` WHERE `theme_id` = 51;',
    'INSERT INTO `atlas_theme_creature` (`theme_id`, `entry`, `pack_role`, `weight`) VALUES',
]
seen = set()
values = []
for entry, name, role in pool:
    if (entry, role) in seen:
        continue
    seen.add((entry, role))
    values.append('(51, %d, %s, 100) -- %s' % (entry, q(role), name))
for i, v in enumerate(values):
    body, comment = v.split(' -- ', 1)
    lines.append(body + (',' if i < len(values) - 1 else ';') + ' -- ' + comment)

lines += [
    '',
    '-- Starting curation: every pool entry untested (it still spawns); the note',
    '-- says what kind of AI it runs. Only rows this file owns are replaced, so',
    "-- statuses set in game with `.atlas curate` survive unless the entry is here.",
    'DELETE FROM `atlas_creature_curation` WHERE `status` = \'untested\' AND `entry` IN (',
] + ['    ' + ', '.join(str(e) for e in sorted(curation)[i:i + 12]) + (',' if i + 12 < len(curation) else ');')
     for i in range(0, len(curation), 12)] + [
    'INSERT IGNORE INTO `atlas_creature_curation` (`entry`, `status`, `note`) VALUES',
]
cur = sorted(curation.items())
for i, (e, (letter, note)) in enumerate(cur):
    lines.append("(%d, 'untested', %s)%s" % (e, q(note), ',' if i < len(cur) - 1 else ';'))

open(out, 'w').write('\n'.join(lines) + '\n')
print(len(values), 'pool rows,', len(cur), 'curation rows')
